'use strict';

//================================
// Typedefs
//================================

/**
 * @typedef {import('./cache.d.ts').Cache} Cache
 * @typedef {import('./cache.d.ts').HeadStyle} HeadStyle
 * @typedef {import('./cache.d.ts').TurnContext} TurnContext
 * @typedef {import('./cache.d.ts').StyleContextPair} StyleContextPair
 */

//================================
// Constants
//================================

/** @type {Map<Element, TurnContext>} */
const parkedBlocks = new Map();

/** @type {WeakMap<Element, HeadStyle>} */
const originalStyles = new WeakMap();

/** @type {Cache} */
const cache = Object.freeze({
  size: size,
  has: has,
  hasNot: hasNot,
  getKeys: getKeys,
  keys: keys,
  clear: clear,
  deleteOutdated: deleteOutdated,
  set: set,
  pop: pop,
  del: del
});

//================================
// Exports
//================================

export default cache;

//================================
// Private Functions
//================================

/**
 * @private
 *
 * Retrieves the total number of currently stored blocks within the active map memory buffer.
 *
 * This utility serves as a clean, read-only interface abstraction to evaluate the capacity metrics
 * of the encapsulated `parkedBlocks` collection, returning the immediate count of tracked data structures.
 *
 * @returns {number} The current count of distinct block items stored inside the map buffer.
 */
function size() {
  return parkedBlocks.size;
}

/**
 * @private
 *
 * Validates whether a specific turn component is actively tracked within the storage map.
 *
 * This lookup utility queries the underlying `parkedBlocks` map memory buffer to determine the membership status of the designated element node.
 *
 * @param {Element} turn - The target component or DOM element node instance to look up.
 *
 * @returns {boolean} `true` if the element exists within the map buffer; otherwise, `false`.
 */
function has(turn) {
  return parkedBlocks.has(turn);
}

/**
 * @private
 *
 * Validates whether a specific turn component is absent from the active storage map.
 *
 * This inverse predicate utility negates the core lookup routine, serving as a clean semantic
 * convenience helper to evaluate missing or untracked element states without cluttering downstream business logic with manual negation operators.
 *
 * @param {Element} turn - The target component or DOM element node instance to evaluate.
 *
 * @returns {boolean} `true` if the element is missing from the map buffer; otherwise, `false`.
 */
function hasNot(turn) {
  return !has(turn);
}

/**
 * @private
 *
 * Resolves all actively tracked map keys and returns them as a standard flat array.
 *
 * This utility captures the internal iterator generated by the `parkedBlocks.keys()` method and immediately expands it into a native JavaScript array using the spread operator. This
 * unlocks clean downstream array manipulation pipelines (such as `.map()`, `.filter()`, or `.forEach()`) on the stored element keys.
 *
 * @returns {Element[]} A flat array containing all active keys currently stored inside the map buffer.
 */
function getKeys() {
  return [ ...keys() ];
}

/**
 * @private
 *
 * Retrieves a native iterator containing all actively tracked keys within the storage map.
 *
 * This utility acts as a low-overhead pass-through to the internal `parkedBlocks.keys()` method.
 * Unlike array-conversion wrappers, it returns a raw, lazy-evaluated `MapIterator`, which is
 * optimal for high-performance memory-efficient streaming, direct evaluation loops, or manual step-throughs.
 *
 * @returns {MapIterator<Element>} A native iterator tracking the current sequence of stored element keys.
 */
function keys() {
  return parkedBlocks.keys();
}

/**
 * @private
 *
 * Flushes all tracked data entries and completely resets the active map memory buffer.
 *
 * This mutation utility wipes the encapsulated `parkedBlocks` instance state clean, freeing up allocated memory by discarding all stored elements and their associated data structures in a single operation.
 *
 * @returns {void}
 */
function clear() {
  parkedBlocks.clear();
}

/**
 * @private
 *
 * Synchronizes the cache buffer by purging elements that are no longer active.
 *
 * This garbage-collection utility cross-references current layout nodes against historical cache records. It wraps the incoming elements into a native `Set` to unlock high-performance O(1) membership lookups.
 * It then streams through all currently cached keys, identifying and permanently deleting any unmapped or outdated components from the internal `parkedBlocks` map memory buffer.
 *
 * @param {Element[]} actualTurns - An array containing the fresh, actively visible elements representing the current layout state.
 *
 * @returns {void}
 */
function deleteOutdated(actualTurns) {
  const actualTurnsSet = new Set(actualTurns);

  for (const turn of keys()) {
    if (!actualTurnsSet.has(turn)) {
      del(turn);
    }
  }
}

/**
 * @private
 *
 * Commits an element's structural styling baseline and runtime execution context to memory.
 *
 * This tracking controller orchestrates a dual-registration lifecycle sequence. It stores the element's original inline layout boundaries inside the `originalStyles` WeakMap cache for
 * downstream style rollbacks. Concurrently, it binds the element to its live virtualization or state properties record inside the `parkedBlocks` memory buffer.
 *
 * @param {Element} turn - The target DOM element component instance acting as the primary cache key.
 * @param {StyleContextPair} styleContextPair - An immutable composite record encapsulating the baseline layout style and tracking context payload.
 *
 * @returns {void}
 */
function set(turn, styleContextPair) {
  originalStyles.set(turn, styleContextPair.style);
  parkedBlocks.set(turn, styleContextPair.context);
}

/**
 * @private
 *
 * Extracts and removes an element's cached layout style and execution context from memory.
 *
 * This destructive retrieval utility captures the current baseline styling snapshot and active runtime properties context associated with the target element. It bundles them into a structured composite
 * pair payload, executes a permanent cache purge via `del` to free up allocated memory layers, and returns the isolated data records.
 *
 * @param {Element} turn - The target DOM element component instance acting as the lookup cache key.
 *
 * @returns {StyleContextPair} A composite token record capturing the deleted element's style snapshot and context payload.
 */
function pop(turn) {
  const style = originalStyles.get(turn);
  const context = parkedBlocks.get(turn);

  del(turn);

  return {
    style: style,
    context: context
  };
}

/**
 * @private
 *
 * Permanently evicts an element's records from all active tracking memory maps.
 *
 * This atomic eviction utility completely detaches the target element from the internal storage layers.
 * It simultaneously deletes its state references from the `parkedBlocks` runtime context map and clears its original inline styles blueprint from the `originalStyles` WeakMap to prevent memory leaks.
 *
 * @param {Element} turn - The target DOM element component instance to evict from cache registries.
 *
 * @returns {void}
 */
function del(turn) {
  parkedBlocks.delete(turn);
  originalStyles.delete(turn);
}
